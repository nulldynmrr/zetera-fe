  // ── Bullet Helpers: Citation Insertion & Concatenation ──
  const getShortAuthorCitation = (authorsStr: string): string => {
    if (!authorsStr) return "Penulis";
    let cleaned = authorsStr.trim();
    // Bersihkan prefix nomor urut seperti "1\t", "1. ", "[1] "
    cleaned = cleaned.replace(/^(\[\d+\]|\d+[\.\)\t\s]+)/, "").trim();

    // Jika sudah memiliki et al (mis. "Law et al." atau "Inkster et al.")
    if (/et\s+al/i.test(cleaned)) {
      const mainAuthor = cleaned.split(/et\s+al/i)[0].trim().replace(/[,.\s]+$/, "");
      return `${mainAuthor || "Penulis"} et al.`;
    }

    // Pisahkan daftar penulis
    const parts = cleaned
      .split(/,\s*(?:and\s+|&\s*)?|\s+and\s+|\s*&\s*/i)
      .map((s) => s.trim())
      .filter(Boolean);

    if (parts.length === 0) return "Penulis";
    if (parts.length === 1) {
      const words = parts[0].split(/\s+/);
      return words.length > 1 ? words[words.length - 1] : words[0];
    } else if (parts.length === 2) {
      const a1 = parts[0].split(/\s+/).pop() || parts[0];
      const a2 = parts[1].split(/\s+/).pop() || parts[1];
      return `${a1} & ${a2}`;
    } else {
      const a1 = parts[0].split(/\s+/).pop() || parts[0];
      return `${a1} et al.`;
    }
  };

  const formatInTextCitation = (journal: Journal, style?: string): string => {
    const normStyle = (style || (project as any)?.citationStyle || "APA").toUpperCase();
    const year = journal.year || new Date().getFullYear();
    const shortAuthor = getShortAuthorCitation(journal.authors || "");

    const idxInPool = poolJournals.findIndex(
      (p) =>
        p.id === journal.id ||
        (p.title && journal.title && p.title.toLowerCase() === journal.title.toLowerCase())
    );
    const numIndex = idxInPool >= 0 ? idxInPool + 1 : 1;

    if (normStyle === "IEEE" || normStyle === "VANCOUVER") {
      return `[${numIndex}]`;
    }
    if (normStyle === "MLA") {
      return `(${shortAuthor} ${year})`;
    }
    return `(${shortAuthor}, ${year})`;
  };

  const handleInsertCitationToActiveBullet = (journal: Journal) => {
    if (!selectedItemId) return;
    const citationTag = formatInTextCitation(journal, (project as any)?.citationStyle);

    const currentSubMap = bulletDrafts[selectedItemId] || {};
    const currentText = currentSubMap[activeBulletIndex] || "";
    const newText = currentText ? `${currentText.trim()} ${citationTag}` : citationTag;

    updateBulletText(selectedItemId, activeBulletIndex, newText);
  };

  const handleCombineBulletsToDraft = async (redirectToProposal: boolean = false) => {
    if (!selectedItemId) return;
    const currentSubMap = bulletDrafts[selectedItemId] || {};
    const bulletEntries = Object.entries(currentSubMap)
      .map(([k, v]) => ({ index: parseInt(k, 10), text: v.trim() }))
      .filter((b) => b.text.length > 0)
      .sort((a, b) => a.index - b.index);

    if (bulletEntries.length === 0) {
      alert("Silakan tuliskan draf pada setidaknya satu butir instruksi di tab Instruksi Riset.");
      return;
    }

    const merged = bulletEntries.map((b) => b.text).join("\n\n");
    setWritingContent(merged);
    await handleSaveWriting(merged);
    setRightTab("write");

    if (redirectToProposal) {
      router.push(`/projects/${projectId}/proposal?tab=bab1`);
    } else {
      alert("✨ Berhasil memulihkan & menggabungkan seluruh poin instruksi ke Naskah Draf Sub-bab!");
    }
  };

